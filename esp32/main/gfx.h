#pragma once
// Tiny drawing library over a 128x96 RGB565 framebuffer. Plain C, no ESP-IDF headers, so the UI
// can also be compiled and rendered on a PC (see tools/render_preview.c).

#include <stdint.h>
#include <stdbool.h>

#define GFX_W 128
#define GFX_H 96

typedef struct {
    // Pixels are stored byte-swapped (big-endian RGB565), the order the SSD1351 expects over SPI.
    uint16_t px[GFX_W * GFX_H];
} gfx_t;

static inline uint16_t gfx_rgb(uint8_t r, uint8_t g, uint8_t b)
{
    return (uint16_t)(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3));
}

/** Linear blend of two RGB565 colours, t in 0..255 (0 = a, 255 = b). */
uint16_t gfx_mix(uint16_t a, uint16_t b, uint8_t t);
/** HSV to RGB565, h in 0..359, s and v in 0..255. */
uint16_t gfx_hsv(int h, uint8_t s, uint8_t v);

void gfx_clear(gfx_t *g, uint16_t color);
void gfx_pixel(gfx_t *g, int x, int y, uint16_t color);
uint16_t gfx_get(const gfx_t *g, int x, int y);
void gfx_fill_rect(gfx_t *g, int x, int y, int w, int h, uint16_t color);
void gfx_rect(gfx_t *g, int x, int y, int w, int h, uint16_t color);
void gfx_round_rect(gfx_t *g, int x, int y, int w, int h, int r, uint16_t color);
void gfx_fill_round_rect(gfx_t *g, int x, int y, int w, int h, int r, uint16_t color);
void gfx_fill_circle(gfx_t *g, int cx, int cy, int r, uint16_t color);
void gfx_circle(gfx_t *g, int cx, int cy, int r, uint16_t color);
void gfx_fill_triangle(gfx_t *g, int x0, int y0, int x1, int y1, int x2, int y2, uint16_t color);
/** Darkens every pixel: keep = 0..255 (255 keeps the image, 0 makes it black). */
void gfx_dim(gfx_t *g, uint8_t keep);

// ---- anti-aliased text (fonts generated by tools/make_fonts.py) ----

typedef struct {
    uint32_t offset;   // into the font's bitmap
    uint8_t w, h;      // inked size in pixels
    int8_t x, y;       // top-left of the ink relative to the pen (y < 0 is above the baseline)
    uint16_t adv16;    // advance in 1/16 pixel
} gfx_glyph_t;

typedef struct {
    const uint8_t *bitmap;      // 4 bits per pixel, high nibble first, rows padded to a byte
    const gfx_glyph_t *glyphs;  // one per character from first to last
    uint8_t first, last;
    uint8_t ascent, descent;
} gfx_font_t;

typedef enum { GFX_LEFT, GFX_CENTER, GFX_RIGHT } gfx_align_t;

/**
 * Draws ASCII text with its baseline at y. x is the left edge, the centre or the right edge,
 * depending on align. tracking16 adds letter spacing in 1/16 px. Pixels outside
 * clip_x0 <= x < clip_x1 are skipped (pass 0, GFX_W for no clipping). Returns the text width.
 */
int gfx_text(gfx_t *g, const gfx_font_t *f, int x, int y, const char *s, uint16_t color,
             gfx_align_t align, int tracking16, int clip_x0, int clip_x1);
/** Width in pixels of the text as gfx_text would draw it. */
int gfx_text_width(const gfx_font_t *f, const char *s, int tracking16);
/** Copies s into out, shortened with "..." if needed so it is at most max_w pixels wide. */
void gfx_text_fit(const gfx_font_t *f, const char *s, int tracking16, int max_w, char *out, int out_size);
