"""Converts the Inter typeface into anti-aliased bitmap fonts for the OLED (esp32/main/fonts_inter.c).

Each glyph is rasterized once with FreeType (via Pillow) and stored with 16 levels of coverage
(4 bits per pixel), so the firmware only blends pixels and needs no font engine.

    pip install pillow
    # Inter variable font, SIL Open Font License:
    #   https://github.com/google/fonts/raw/main/ofl/inter/Inter%5Bopsz,wght%5D.ttf
    python make_fonts.py path/to/Inter[opsz,wght].ttf ../main

The generated C file is committed, so building the firmware does not need Pillow or the TTF.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
DIGITS = " 0123456789"

# name, pixel size, weight, characters, purpose
FONTS = [
    ("inter_9_semibold", 9, 600, ASCII, "header: category, S/R"),
    ("inter_10_regular", 10, 400, ASCII, "artist, secondary text"),
    ("inter_10_semibold", 10, 600, ASCII, "volume number, flash labels, status text"),
    ("inter_17_bold", 17, 700, ASCII, "song title, offline headline"),
    ("inter_26_bold", 26, 700, DIGITS, "volume number on the knob overlay"),
]


def load(ttf, size, weight, scale=1):
    """Loads Inter at size * scale pixels; optical size and weight are set for the target size."""
    font = ImageFont.truetype(str(ttf), size * scale)
    axes = font.get_variation_axes()
    values = []
    for axis in axes:
        name = axis["name"].decode() if isinstance(axis["name"], bytes) else axis["name"]
        if name.lower().startswith("opt"):  # optical size follows the pixel size, like browsers do
            values.append(max(axis["minimum"], min(axis["maximum"], size)))
        elif name.lower().startswith("weight"):
            values.append(weight)
        else:
            values.append(axis["default"])
    font.set_variation_by_axes(values)
    return font


SS = 4  # supersampling factor


def rasterize(big, ch):
    """Renders ch with the font at SS times the size and box-filters it down.

    This avoids FreeType's hinting, which at 9-10 px snaps every advance to a whole pixel and makes
    letter gaps uneven; the result matches how browsers draw small text. Returns (rows of 0-15
    coverage values, x offset, y offset from the baseline, advance in 1/16 px).
    """
    advance16 = round(big.getlength(ch) * 16 / SS)
    left, top, right, bottom = big.getbbox(ch, anchor="ls")
    if right <= left or bottom <= top:
        return [], 0, 0, advance16
    # pen origin on a multiple of SS, so it lands exactly on a pixel after downsampling
    ox = (-(left // SS) + 1) * SS
    oy = (-(top // SS) + 1) * SS
    w = -(-(ox + right) // SS) * SS + SS
    h = -(-(oy + bottom) // SS) * SS + SS
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((ox, oy), ch, font=big, fill=255, anchor="ls")
    small = img.reduce(SS)
    box = small.getbbox()
    if box is None:
        return [], 0, 0, advance16
    crop = small.crop(box)
    x_off = box[0] - ox // SS
    y_off = box[1] - oy // SS
    rows = [[round(crop.getpixel((x, y)) / 17) for x in range(crop.width)] for y in range(crop.height)]
    # drop rows/columns that rounded to nothing
    while rows and not any(rows[0]):
        rows.pop(0)
        y_off += 1
    while rows and not any(rows[-1]):
        rows.pop()
    if not rows:
        return [], 0, 0, advance16
    while not any(r[0] for r in rows):
        rows = [r[1:] for r in rows]
        x_off += 1
    while not any(r[-1] for r in rows):
        rows = [r[:-1] for r in rows]
    return rows, x_off, y_off, advance16


def pack(rows):
    """4 bits per pixel, high nibble first, each row padded to a whole byte."""
    out = []
    for row in rows:
        for i in range(0, len(row), 2):
            hi = row[i]
            lo = row[i + 1] if i + 1 < len(row) else 0
            out.append((hi << 4) | lo)
    return out


def generate(ttf, out_dir):
    c_lines = [
        "// Generated by esp32/tools/make_fonts.py from Inter (SIL Open Font License 1.1,",
        "// see fonts/OFL-Inter.txt). Do not edit by hand.",
        "",
        '#include "fonts_inter.h"',
        "",
    ]
    h_lines = [
        "#pragma once",
        "// Anti-aliased Inter fonts for the OLED. Generated by esp32/tools/make_fonts.py.",
        "",
        '#include "gfx.h"',
        "",
    ]
    total = 0
    for name, size, weight, chars, purpose in FONTS:
        font = load(ttf, size, weight, SS)
        ascent, descent = (round(v / SS) for v in font.getmetrics())
        first, last = ord(min(chars)), ord(max(chars))
        bitmap, glyphs = [], []
        for code in range(first, last + 1):
            ch = chr(code)
            if ch not in chars:
                glyphs.append((len(bitmap), 0, 0, 0, 0, 0))
                continue
            rows, x_off, y_off, adv16 = rasterize(font, ch)
            w = len(rows[0]) if rows else 0
            glyphs.append((len(bitmap), w, len(rows), x_off, y_off, adv16))
            bitmap.extend(pack(rows))
        total += len(bitmap) + len(glyphs) * 8

        c_lines.append(f"// {name}: {size} px, weight {weight}. {purpose}")
        c_lines.append(f"static const uint8_t {name}_bitmap[{max(1, len(bitmap))}] = {{")
        data = bitmap or [0]
        for i in range(0, len(data), 16):
            c_lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        c_lines.append("};")
        c_lines.append(f"static const gfx_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for code, (off, w, h, xo, yo, adv) in zip(range(first, last + 1), glyphs):
            label = repr(chr(code)) if chr(code) != "\\" else "backslash"
            c_lines.append(f"    {{{off}, {w}, {h}, {xo}, {yo}, {adv}}}, // {label}")
        c_lines.append("};")
        c_lines.append(f"const gfx_font_t {name} = {{")
        c_lines.append(f"    .bitmap = {name}_bitmap, .glyphs = {name}_glyphs,")
        c_lines.append(f"    .first = {first}, .last = {last}, .ascent = {ascent}, .descent = {descent},")
        c_lines.append("};")
        c_lines.append("")
        h_lines.append(f"extern const gfx_font_t {name}; // {size} px, weight {weight}: {purpose}")

    out = Path(out_dir)
    (out / "fonts_inter.c").write_text("\n".join(c_lines) + "\n", encoding="utf-8")
    (out / "fonts_inter.h").write_text("\n".join(h_lines) + "\n", encoding="utf-8")
    print(f"wrote {out / 'fonts_inter.c'} ({total} bytes of font data)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    generate(Path(sys.argv[1]), sys.argv[2])
